"""Writes the Python API pages of the docs site (lila-dcc.github.io, docs/python/) from the command registry and the lila
package, so the reference online and in the Docs panel is the same one the script editor shows.

    lila.exe -b -c "import lila._apipages as p; p.write(r'X:/Lila-DCC/docs')"

Run it from the GUI's script editor instead to include commands that only register with the UI. Every .md under
docs/python/ is generated: fix the text in the command or Python definitions, never in the pages.
"""

import os
import re

import _lila

from . import _apidoc

FOLDER = "python"
OPS = "lila.ops"
_HEADER = "<!-- Generated by Lila from its command registry and Python API. Do not edit. -->"


def write(docs_dir):
    """Rewrites docs_dir/python/ and removes pages that no longer have a symbol. Returns the paths written."""
    out_dir = os.path.join(docs_dir, FOLDER)
    os.makedirs(out_dir, exist_ok=True)
    pages = render()
    written = []
    for name, text in pages.items():
        path = os.path.join(out_dir, name)
        _write_if_changed(path, text)
        written.append(path)
    for name in os.listdir(out_dir):
        if name.endswith(".md") and name not in pages:
            os.remove(os.path.join(out_dir, name))
    return written


def render():
    """{file name: markdown} for every page."""
    modules = [m for m in _apidoc.collect() if m["members"] or m["name"] == "lila"]
    commands = sorted(_lila.commands(), key=lambda s: s["name"].lower())
    pages = {"README.md": _home(modules, commands), f"{OPS}.md": _ops_page(commands)}
    for mod in modules:
        pages[f"{mod['name']}.md"] = _module_page(mod)
    return pages


def page_link(page, heading=None):
    """A link both docsify and the Docs panel resolve: from the docs root, with ?id= for a heading."""
    link = f"{FOLDER}/{page}.md"
    return f"{link}?id={slug(heading)}" if heading else link


def slug(heading):
    """docsify's heading id, as lila::ui::docs::slug computes it."""
    s = re.sub(r"<[^>]*>", "", heading.strip().lower())
    s = re.sub(r"[\\'!\"#$%&()*+,./:;<=>?@\[\]^`{|}~\u2000-\u206f]", "", s)
    return re.sub(r"\s+", "-", s)


def _home(modules, commands):
    lines = [
        _HEADER,
        "",
        "# Python API",
        "",
        "Every command is a Python function. In the script editor and the command line (**Ctrl+\\`**) commands are available by bare name; in a module, `import lila` and call `lila.ops.<command>`.",
        "",
        "```python",
        'polyCube(name="crate", width=2)',
        'lila.ops.parent("arm_l", "spine_03")',
        "```",
        "",
        "Commands that take objects use the selection when none are passed.",
        "",
        "| Page | Contents |",
        "| --- | --- |",
        f"| [{OPS}]({page_link(OPS)}) | All {len(commands)} commands and their flags. |",
    ]
    for mod in modules:
        lines.append(f"| [{mod['name']}]({page_link(mod['name'])}) | {_cell(_summary(mod['doc']))} |")
    lines.append("")
    return "\n".join(lines)


def _ops_page(commands):
    groups = {}
    for spec in commands:
        groups.setdefault(spec.get("owner") or "", []).append(spec)
    lines = [_HEADER, "", f"# {OPS}", "", "Every command, by bare name or as `lila.ops.<name>`. Flags are keyword arguments; most also take a short form.", ""]
    for owner in sorted(groups, key=lambda o: (o != "", o.lower())):
        lines += [f"## {'Built-in commands' if not owner else owner + ' extension'}", ""]
        if owner:
            lines += [f"Available when the {owner} extension is loaded.", ""]
        for spec in groups[owner]:
            lines += _command(spec)
    return "\n".join(lines)


def _command(spec):
    lines = [f"### {spec['name']}", ""]
    doc = spec["doc"].strip()
    if doc:
        lines += [_text(doc), ""]
    if spec["positional"]:
        lines += [f"**Objects:** {_flat(spec['positional'])}", ""]
    if spec["flags"]:
        lines += ["| Flag | Short | Type | Default | Description |", "| --- | --- | --- | --- | --- |"]
        for f in spec["flags"]:
            short = f.get("short") or ""
            short = f"`{short}`" if short and short != f["name"] else ""
            desc = _flat(f.get("doc"))
            if f.get("choices") and not all(str(c) in desc for c in f["choices"]):
                desc += (" " if desc else "") + "One of " + ", ".join(f"`{c}`" for c in f["choices"]) + "."
            if f.get("example"):
                desc += (" " if desc else "") + f"Example: `{f['example']}`"
            lines.append(f"| `{f['name']}` | {short} | {f['type']} | {_default(f.get('default'))} | {_cell(desc)} |")
        lines.append("")
    if not spec.get("undoable", True):
        lines += ["Not undoable.", ""]
    for example in spec.get("examples") or []:
        lines += ["```python", example.strip("\n"), "```", ""]
    return lines


def _module_page(mod):
    lines = [_HEADER, "", f"# {mod['name']}", ""]
    if mod["doc"]:
        lines += [_text(mod["doc"]), ""]
    members = sorted(mod["members"], key=lambda m: (m["kind"] != "class", m["name"].lower()))
    for m in members:
        lines += _member(m, "##")
        if m["kind"] == "class":
            for sub in m.get("members") or []:
                lines += _member(sub, "###", prefix=m["name"] + ".")
    return "\n".join(lines)


def _member(m, level, prefix=""):
    lines = [f"{level} {prefix}{m['name']}", ""]
    kind = m["kind"]
    if kind == "class" and m.get("bases"):
        lines += ["Inherits " + ", ".join(f"`{b}`" for b in m["bases"]) + ".", ""]
    sigs = m.get("signature") or []
    if kind == "attribute":
        sigs = [f"{m['name']} = {m.get('value', '')}"]
    if kind == "property" and not sigs:
        sigs = [m["name"]]
    if sigs:
        lines += ["```python", *sigs, "```", ""]
    tags = []
    if kind in ("staticmethod", "classmethod"):
        tags.append("Static method." if kind == "staticmethod" else "Class method.")
    if kind == "property" and m.get("readonly"):
        tags.append("Read only.")
    if tags:
        lines += [" ".join(tags), ""]
    if m.get("doc"):
        lines += [_text(m["doc"]), ""]
    return lines


_CODE_START = re.compile(r"(import|from|with|for|if)\s|>>>|\.\.\.")
_STATEMENT = re.compile(r"[\w.\[\]\"']+ = .+|[\w.]+\(.*\)")
_LIST_ITEM = re.compile(r"([-*+]|\d+[.)])\s")
# "name: what it is", one per line, as in a parameter list.
_TERM = re.compile(r"\w+: ")
# nanobind puts a bare signature in some docs (property getters, static attributes).
_NB_GETTER = re.compile(r"^\([^\n]*\) -> [^\n]*$", re.M)


def _is_code(line):
    """A flush-left docstring line that reads as Python rather than prose."""
    s = line.split("  #", 1)[0].strip()
    return bool(_CODE_START.match(s) or _STATEMENT.fullmatch(s))


def _text(doc):
    """
    A docstring as markdown. Indented runs and paragraphs of Python become code blocks; prose paragraphs are unwrapped
    to one line each.
    """
    out = []
    for para in re.split(r"\n\s*\n", _NB_GETTER.sub("", str(doc)).strip("\n")):
        lines = para.expandtabs(4).splitlines()
        # Runs of indented and flush-left lines: "Args:" then its indented entries is two runs.
        runs = []
        for l in lines:
            indented = l.startswith(" ")
            if runs and runs[-1][0] == indented:
                runs[-1][1].append(l)
            else:
                runs.append((indented, [l]))
        for indented, run in runs:
            if indented or all(_is_code(l) for l in run):
                width = min(len(l) - len(l.lstrip()) for l in run)
                code = [l[width:] for l in run]
                # Code paragraphs in a row are one example.
                if out[-2:] == ["```", ""]:
                    out[-2:] = ["", *code, "```", ""]
                else:
                    out += ["```", *code, "```", ""]
                continue
            joined = []
            terms = sum(1 for l in run if _TERM.match(l.strip())) > 1
            for l in run:
                s = l.strip()
                if terms and _TERM.match(s):
                    joined.append("- " + s)
                elif joined and not _LIST_ITEM.match(s) and not joined[-1].endswith(":"):
                    joined[-1] += " " + s
                else:
                    joined.append(s)
            out += joined + [""]
    return "\n".join(out).strip("\n")


def _summary(doc):
    return (doc or "").strip().split("\n\n", 1)[0].replace("\n", " ")


def _flat(text):
    return " ".join(str(text or "").split())


def _cell(text):
    return text.replace("|", "\\|")


def _default(value):
    if value is None or value == "" or value == [] or value == {}:
        return ""
    return _cell(f"`{value!r}`")


def _write_if_changed(path, text):
    if os.path.isfile(path):
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
