"""Writes ops.pyi from the live command registry so editors and basedpyright see typed commands.

Also writes _namespace/__builtins__.pyi, which the script editor's language server reads as extra builtins: the
bare names _startup puts in the interactive namespace (xform(), Node, ...), so calls to them get signatures and
keyword completions. _namespace/ruff_builtins.toml declares the same names to ruff, so it does not flag them as
undefined (F821).
"""

import builtins
import keyword
import os

import _lila

from ._startup import API_NAMES

_TYPES = {"bool": "bool", "int": "int", "float": "float", "str": "str", "tuple[float, float, float]": "Sequence[float]", "list": "Sequence[Any]"}


def _sentence(text):
    text = " ".join(str(text or "").split())
    return text if not text or text[-1] in ".!?" else text + "."


def _flag_doc(f):
    parts = [_sentence(f.get("doc"))]
    if f.get("short") and f["short"] != f["name"]:
        parts.append(f"Short form {f['short']}.")
    if f.get("choices"):
        parts.append("One of " + ", ".join(repr(c) for c in f["choices"]) + ".")
    default = f.get("default")
    if default is not None and default != "" and default != [] and default != {}:
        parts.append(f"Default {default!r}.")
    if f.get("example"):
        parts.append(f"Example: `{f['example']}`")
    return " ".join(p for p in parts if p)


def command_doc(spec):
    """The command's docstring: its doc, an Args section with every flag, then Examples. Shared by ops and the stubs."""
    out = [spec["doc"].strip()]
    args = []
    if spec["positional"]:
        args.append(f"    objects: {_sentence(spec['positional'])}")
    for f in spec["flags"]:
        args.append(f"    {f['name']}: {_flag_doc(f)}".rstrip())
    if args:
        out += ["", "Args:"] + args
    examples = spec.get("examples") or []
    if examples:
        out += ["", "Examples:"]
        for i, e in enumerate(examples):
            if i:
                out.append("")
            out += [f"    {line}" if line.strip() else "" for line in e.strip("\n").splitlines()]
    return "\n".join(out)


def _docstring(spec):
    lines = command_doc(spec).replace("\\", "\\\\").replace('"""', "'''").split("\n")
    if len(lines) == 1:
        return lines[0]
    return "\n".join([lines[0]] + [f"    {line}" if line else "" for line in lines[1:]] + ["    "])


def _render():
    lines = [
        "# Generated by Lila from the command registry. Do not edit.",
        "from typing import Any, Sequence",
        "",
    ]
    for spec in sorted(_lila.commands(), key=lambda s: s["name"]):
        params = ["*objects: Any"] if spec["positional"] else []
        reserved = False
        shorts = []
        taken = {f["name"] for f in spec["flags"]}
        for f in spec["flags"]:
            # A flag named like a Python keyword (async) is passed as **{"async": True}.
            if keyword.iskeyword(f["name"]):
                reserved = True
                continue
            t = _TYPES.get(f["type"], "Any")
            params.append(f"{f['name']}: {t} | None = None")
            short = f.get("short")
            if short and short not in taken and short.isidentifier() and not keyword.iskeyword(short):
                taken.add(short)
                shorts.append(f"{short}: {t} | None = None")
        # Short forms last and keyword-only, so the long names lead the signature and positional calls stay as before.
        if shorts:
            params += ([] if spec["positional"] else ["*"]) + shorts
        if reserved:
            params.append("**flags: Any")
        lines.append(f"def {spec['name']}({', '.join(params)}) -> Any:")
        lines.append(f'    """{_docstring(spec)}"""')
        lines.append("")
    lines.append("def refresh() -> None: ...")
    lines.append("")
    return "\n".join(lines)


def _command_names():
    # Python builtins win over commands of the same name, as in _startup.expose_commands.
    return sorted(s["name"] for s in _lila.commands() if not hasattr(builtins, s["name"]))


def namespace_names():
    """Every bare name _startup.boot puts in the interactive namespace."""
    return ["lila", "ops", *API_NAMES, *_command_names()]


def _render_builtins():
    lines = [
        "# Generated by Lila: the script editor's interactive namespace. Do not edit.",
        "import lila as lila",
        "from lila import ops as ops",
        f"from lila import {', '.join(f'{n} as {n}' for n in API_NAMES)}",
    ]
    lines += [f"from lila.ops import {n} as {n}" for n in _command_names()]
    lines.append("")
    return "\n".join(lines)


def _render_ruff_builtins():
    # One KEY = VALUE line: the script editor passes it to ruff as a --config override.
    return "builtins = [" + ", ".join(f'"{n}"' for n in namespace_names()) + "]\n"


def _write_if_changed(path, text, force):
    try:
        if not force and os.path.isfile(path):
            with open(path, encoding="utf-8") as f:
                if f.read() == text:
                    return path
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    except OSError:
        return None
    return path


def namespace_dir():
    """The directory holding __builtins__.pyi; the script editor adds it to the language server's extraPaths."""
    return os.path.join(os.path.dirname(__file__), "_namespace")


def write(force=False):
    """Rewrites the stubs only when the registry changed. Silently skips read-only installs."""
    _write_if_changed(os.path.join(namespace_dir(), "__builtins__.pyi"), _render_builtins(), force)
    _write_if_changed(os.path.join(namespace_dir(), "ruff_builtins.toml"), _render_ruff_builtins(), force)
    return _write_if_changed(os.path.join(os.path.dirname(__file__), "ops.pyi"), _render(), force)
